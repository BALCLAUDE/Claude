"""CLI: python -m budget.etl <step> [options]

Steps
  fetch        download R-1/P-1/O-1/M-1 workbooks into budget/raw/ (comptroller.war.gov)
  build        create budget/build/budget.sqlite from taxonomy + exhibits + mandatory funding,
               classify lines, run checks and write the dashboard data file
  all          fetch, then build
  sample       build a demo database from synthetic exhibits (NOT real budget data)
  classify     re-run classification on an existing database
"""
from __future__ import annotations

import argparse
import base64
import datetime as dt
import shutil
import sys
import tempfile
from pathlib import Path

from . import budget_exhibits, classify, reconciliation, sample, taxonomy
from .common import (BUDGET_DIR, BUILD_DIR, DEFAULT_DB, FIRST_FY, LAST_FY, RAW_DIR, BuildError, connect,
                     create_db, set_meta)

DASHBOARD_DATA = BUDGET_DIR / "dashboard" / "data.js"


def build(db_path: Path, raw_dir: Path, allow_mismatch: bool = False, is_sample: bool = False,
          mandatory_rows=None, toplines=None, dashboard_data: Path | None = DASHBOARD_DATA) -> dict:
    tmp = db_path.with_suffix(".tmp.sqlite")
    con = create_db(tmp)
    try:
        print("taxonomy")
        tax = taxonomy.read()
        t_stats = taxonomy.load(con, tax)
        print(f"  {t_stats}")
        print(f"exhibits from {raw_dir}")
        e_stats = budget_exhibits.load(con, raw_dir, allow_mismatch=allow_mismatch, toplines=toplines,
                                       as_of=dt.date.today().isoformat())
        if not e_stats["files"]:
            raise BuildError(f"no exhibit workbooks found under {raw_dir}; run `python -m budget.etl fetch` "
                             "or drop FY<year>_r1.xlsx etc. into budget/raw/FY<year>/")
        print("mandatory funding")
        rows = reconciliation.read() if mandatory_rows is None else mandatory_rows
        m_stats = reconciliation.load(con, rows)
        print(f"  {m_stats}")
        print("classify")
        c_stats = classify.classify(con)
        stale = c_stats.pop("stale_overrides")
        print(f"  {c_stats}")
        if stale:
            print(f"  warning: {len(stale)} override(s) name lines not in the data: {stale[:5]}")
        books = [r[0] for r in con.execute("SELECT DISTINCT book_fy FROM budget_values WHERE book_fy IS NOT NULL ORDER BY 1")]
        set_meta(con, built=dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                 sample=int(is_sample), first_fy=FIRST_FY, last_fy=LAST_FY,
                 books=",".join(map(str, books)), taxonomy_edition=tax.get("edition"),
                 taxonomy_as_of=tax.get("asOf"), units="thousands of dollars ($K)",
                 exhibit_checks=e_stats["checks"], exhibit_mismatches=len(e_stats["mismatches"]))
        con.commit()
        con.execute("VACUUM")
        con.close()
        tmp.replace(db_path)
    except Exception:
        con.close()
        tmp.unlink(missing_ok=True)
        raise
    if dashboard_data:
        write_dashboard_data(db_path, dashboard_data)
    return {"taxonomy": t_stats, "exhibits": e_stats, "mandatory": m_stats, "classify": c_stats}


def write_dashboard_data(db_path: Path, out: Path = DASHBOARD_DATA) -> None:
    """Embeds the database as base64 so the dashboard opens straight from disk (file://)."""
    b64 = base64.b64encode(db_path.read_bytes()).decode()
    out.write_text("/* Generated by python -m budget.etl. Do not edit. */\n"
                   f"window.BUDGET_DB_B64 = \"{b64}\";\n")
    print(f"wrote {out} ({len(b64) // 1024} KB)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m budget.etl", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("step", choices=["fetch", "build", "all", "sample", "classify"])
    ap.add_argument("--db", type=Path, default=None, help=f"output database (default {DEFAULT_DB})")
    ap.add_argument("--raw", type=Path, default=RAW_DIR, help="directory of FY<year>/ exhibit workbooks")
    ap.add_argument("--books", default=f"{FIRST_FY}-{LAST_FY}", help="book years to fetch, e.g. 2025-2027")
    ap.add_argument("--allow-mismatch", action="store_true", help="record, but do not fail on, total mismatches")
    ap.add_argument("--no-dashboard", action="store_true", help="do not write dashboard/data.js")
    args = ap.parse_args(argv)
    lo, _, hi = args.books.partition("-")
    books = range(int(lo), int(hi or lo) + 1)
    dash = None if args.no_dashboard else DASHBOARD_DATA
    try:
        if args.step in ("fetch", "all"):
            print(f"fetch FY{books.start}-FY{books.stop - 1}")
            failures = budget_exhibits.fetch(args.raw, books=books)
            if failures:
                print(f"{len(failures)} workbook(s) could not be downloaded; the build uses what is in {args.raw}",
                      file=sys.stderr)
        if args.step in ("build", "all"):
            build(args.db or DEFAULT_DB, args.raw, allow_mismatch=args.allow_mismatch, dashboard_data=dash)
        if args.step == "sample":
            with tempfile.TemporaryDirectory() as d:
                sample.write_all(Path(d))
                build(args.db or BUILD_DIR / "budget.sample.sqlite", Path(d), is_sample=True,
                      mandatory_rows=sample.SAMPLE_MANDATORY, toplines=[], dashboard_data=dash)
        if args.step == "classify":
            con = connect(args.db or DEFAULT_DB)
            for t in ("line_sector_map", "line_status", "line_program", "review_queue"):
                con.execute(f"DELETE FROM {t} WHERE " + ("method != 'human' OR method IS NULL" if t in ("line_sector_map", "line_status")
                                                        else "method != 'human'" if t == "line_program" else "1"))
            print(classify.classify(con))
            con.commit()
    except BuildError as e:
        print(f"BUILD FAILED: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
